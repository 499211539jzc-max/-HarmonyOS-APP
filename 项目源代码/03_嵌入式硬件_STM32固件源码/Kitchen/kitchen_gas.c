#include "stm32l4xx_hal.h"                  // Device header


/*----------------------------------------------------------------------------
* @文件名        : mq_5
* @描述          : 可燃气体传感器配置相关函数
* @作者          : 物联网项目组
* @日期          : 2023/04/01
* @版本          : V0.0.2
******************************************************************************
本驱动函数使用指导流程：
1、添加本驱动的.c和.h文件
2、在main.c中调用MQ5_Init函数进行GPIO初始化，这里采用PD15作为信号输入口
3、通过调用MQ5_Read_State的返回值读取传感器值
******************************************************************************/

/*****************************IO引脚宏定义**************************************/	
#define MQ5_Pin         GPIO_PIN_15
#define MQ5_GPIO_Port   GPIOD

/*****************************IO操作函数****************************************/	
#define	MQ5_STATE()     HAL_GPIO_ReadPin(MQ5_GPIO_Port, MQ5_Pin)     

/********************************************************************************
* 名    称：MQ5_Init
* 功    能：初始化MQ5
* 参数说明：无
* 返 回 值：无
* 说    明：配置MQ5的IO引脚
* 调用方法：外部函数
********************************************************************************/
void MQ5_Init(void)
{
    GPIO_InitTypeDef GPIO_InitStruct;

    __HAL_RCC_GPIOD_CLK_ENABLE();         //使能GPIOD的工作时钟

    /* 配置PB15引脚 */
    GPIO_InitStruct.Pin = MQ5_Pin;
    GPIO_InitStruct.Mode = GPIO_MODE_INPUT;
    GPIO_InitStruct.Pull = GPIO_PULLUP;
    HAL_GPIO_Init(MQ5_GPIO_Port, &GPIO_InitStruct);
}

/********************************************************************************
* 名    称：MQ5_Read_State
* 功    能：读取MQ5的状态
* 参数说明：无
* 返 回 值：MQ5_STATE:  1 无烟
                        0 有烟
* 说    明：用于检测烟雾，达到一定烟雾浓度，会置高
* 调用方法：外部函数
********************************************************************************/
uint8_t MQ5_Read_State(void)
{
    return MQ5_STATE();
}
